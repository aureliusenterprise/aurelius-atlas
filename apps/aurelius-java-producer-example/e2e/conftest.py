@pytest.fixture(scope="session")
def keycloak(observability: DockerCompose) -> Generator[DockerCompose]:
    """
    Return a Docker Compose instance for the Keycloak service.

    The dev Kafka broker validates OAUTHBEARER tokens against the `kafka` realm imported here.

    Note: This fixture starts the Keycloak service if it's not already running, but does not stop it after the tests.
    This allows the service to be reused across multiple test sessions, but may require manual cleanup if the service
    is no longer needed.
    """
    _ = observability  # Ensure that the observability services are started before starting Keycloak

    context = Path(__file__).parents[3].absolute() / "dev" / "keycloak"
    # Same .env-interpolation guard as the kafka fixture below: this project's
    # own TLS_TRUSTSTORE_PASSWORD would leave Keycloak unable to open its
    # truststore when the shared stack is (re)started.
    saved = os.environ.pop("TLS_TRUSTSTORE_PASSWORD", None)
    try:
        compose = DockerCompose(context=context)

        compose.start()

        yield compose.waiting_for(
            {
                "keycloak": HealthcheckWaitStrategy(),
            },
        )
    finally:
        if saved is not None:
            os.environ["TLS_TRUSTSTORE_PASSWORD"] = saved


@pytest.fixture(scope="session")
def kafka(keycloak: DockerCompose) -> Generator[DockerCompose]:
    """
    Return a Docker Compose instance for the Kafka service.

    The Keycloak stack is started first: the broker's OAUTHBEARER listeners validate tokens against it.

    Note: This fixture starts the Kafka service if it's not already running, but does not stop it after the tests.
    This allows the service to be reused across multiple test sessions, but may require manual cleanup if the service is
    no longer needed.
    """
    _ = keycloak  # Ensure the OAuth issuer is up before Kafka clients authenticate

    context = Path(__file__).parents[3].absolute() / "dev" / "kafka"
    # Docker Compose interpolates an infra project's .env with process-env
    # precedence: this project's own TLS_TRUSTSTORE_PASSWORD (random per
    # project) would override dev/kafka's and leave the broker unable to open
    # its keystore. Strip it while the shared stack is (re)started.
    saved = os.environ.pop("TLS_TRUSTSTORE_PASSWORD", None)
    try:
        compose = DockerCompose(context=context)

        compose.start()

        yield compose.waiting_for(
            {
                "broker": HealthcheckWaitStrategy(),
                "schema-registry": HealthcheckWaitStrategy(),
            },
        )
    finally:
        if saved is not None:
            os.environ["TLS_TRUSTSTORE_PASSWORD"] = saved


