@pytest.fixture
def connection(compose: DockerCompose) -> Generator[http.client.HTTPSConnection]:
    """Return an HTTPS connection to the API."""
    host, port = compose.get_service_host_and_port("aurelius-atlas-fastapi-example", 8000)

    if not (host and port):
        message = "Service not found in Docker Compose"
        raise ValueError(message)

    context = ssl.create_default_context(cafile=str(CA_FILE))
    connection = http.client.HTTPSConnection(
        "localhost" if host in ("0.0.0.0", "::") else host,  # noqa: S104
        port,
        context=context,
    )

    yield connection

    connection.close()


